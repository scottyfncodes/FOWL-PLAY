import type { LocusId } from '../genetics/loci';

/**
 * Real-world chicken breeds, each given a simplified game genotype that
 * reproduces the breed's signature look inside FOWL PLAY's genetics model.
 *
 * Descriptions stick to widely-reported facts and stay deliberately short.
 * The genotypes are game constructs and are not claims about real poultry
 * genetics.
 */
export type GenotypeSpec = Partial<Record<LocusId, string>>;

export interface BreedDef {
  id: string;
  name: string;
  /** Country or region of origin. */
  origin: string;
  description: string;
  /** Egg colour, in words, for the almanac card. */
  eggs: string;
  /** Short notable traits for the almanac card. */
  notable: string[];
  /** 1 = common and cheap in the hatchery, 4 = exotic and pricey. */
  tier: 1 | 2 | 3 | 4;
  genotype: GenotypeSpec;
  /**
   * Trait tags that make a bred chicken count as a look-alike for this breed.
   * Alternatives within one entry are separated by `|`.
   */
  signature: string[];
}

const size = (n: number): GenotypeSpec => {
  const pairs: string[] = [];
  let left = n;
  for (let i = 0; i < 3; i++) {
    const c = Math.max(0, Math.min(2, left));
    pairs.push(c === 2 ? 'L/L' : c === 1 ? 'L/s' : 's/s');
    left -= c;
  }
  return { size1: pairs[0], size2: pairs[1], size3: pairs[2] };
};
const fluff = (n: number): GenotypeSpec => ({
  fluff1: n >= 2 ? 'Fl/Fl' : n === 1 ? 'Fl/fl' : 'fl/fl',
  fluff2: n >= 4 ? 'Fl/Fl' : n === 3 ? 'Fl/fl' : 'fl/fl',
});
const legs = (n: number): GenotypeSpec => ({
  legFeather1: n >= 2 ? 'Pti/Pti' : n === 1 ? 'Pti/pti+' : 'pti+/pti+',
  legFeather2: n >= 4 ? 'Pti/Pti' : n === 3 ? 'Pti/pti+' : 'pti+/pti+',
});
const brown = (n: number): GenotypeSpec => ({
  brown1: n >= 2 ? 'Br/Br' : n === 1 ? 'Br/br' : 'br/br',
  brown2: n >= 4 ? 'Br/Br' : n === 3 ? 'Br/br' : 'br/br',
  brown3: n >= 6 ? 'Br/Br' : n === 5 ? 'Br/br' : 'br/br',
});
const pea: GenotypeSpec = { peaComb: 'P/P' };
const rose: GenotypeSpec = { roseComb: 'R/R' };
const walnut: GenotypeSpec = { peaComb: 'P/P', roseComb: 'R/R' };
const vcomb: GenotypeSpec = { duplexComb: 'D/D' };
const black: GenotypeSpec = { base: 'E/E' };
const per = (temper: string, social: string, flair = 'none/none'): GenotypeSpec => ({ temper, social, flair });

